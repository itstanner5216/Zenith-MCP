// ── coverage accounting ────────────────────────────────────────────────────

const OFFSETS_SEEN = new Set<number>();
const RANGES_SEEN = new Set<string>();

function seenRange(start: number, end: number): void {
    OFFSETS_SEEN.add(start);
    OFFSETS_SEEN.add(end);
    RANGES_SEEN.add(`${start}:${end}`);
}

afterAll(() => {
    console.log(
        `[coverage] ${RANGES_SEEN.size} distinct byte ranges over ${OFFSETS_SEEN.size} distinct byte offsets exercised`,
    );
});

// ── temp files, tracked so nothing is left behind ─────────────────────────

const TMP_ROOT = fs.mkdtempSync(path.join(os.tmpdir(), 'stride-source-'));
const OPEN_SOURCES: StrideSource[] = [];

function tmpPath(name: string): string {
    return path.join(TMP_ROOT, name);
}

/** A FileSource that is closed after the test, whatever the test does. */
function fileSourceOver(name: string, bytes: Buffer, pageCache?: number): FileSource {
    const p = tmpPath(name);
    fs.writeFileSync(p, bytes);
    const src = pageCache === undefined ? new FileSource(p) : new FileSource(p, pageCache);
    OPEN_SOURCES.push(src);
    return src;
}

afterEach(() => {
    while (OPEN_SOURCES.length > 0) {
        const src = OPEN_SOURCES.pop();
        if (src !== undefined) src.close();
    }
});

afterAll(() => {
    fs.rmSync(TMP_ROOT, { recursive: true, force: true });
});

// ── failure helpers ────────────────────────────────────────────────────────

const FAILURES: readonly StrideFailure[] = [
    'not_found', 'bad_pointer', 'bad_cursor', 'malformed_json',
    'not_a_container', 'not_a_scalar', 'empty_query', 'too_large',
];

type Outcome =
    | { readonly kind: 'returned' }
    | { readonly kind: 'stride'; readonly error: StrideError }
    | { readonly kind: 'other'; readonly error: unknown };

function run(fn: () => void): Outcome {
    try {
        fn();
        return { kind: 'returned' };
    } catch (e) {
        return e instanceof StrideError ? { kind: 'stride', error: e } : { kind: 'other', error: e };
    }
}

function describeOutcome(o: Outcome): string {
    if (o.kind === 'returned') return 'returned normally';
    if (o.kind === 'stride') return `StrideError(${o.error.failure})`;
    const e = o.error;
    return e instanceof Error ? `bare ${e.name}: ${e.message}` : `thrown non-Error: ${String(e)}`;
}

function expectStrideFailure(fn: () => void, failure: StrideFailure, label: string): void {
    const o = run(fn);
    expect(describeOutcome(o), `${label}: expected StrideError(${failure}), got ${describeOutcome(o)}`)
        .toBe(`StrideError(${failure})`);
    if (o.kind !== 'stride') return;
    expect(
        FAILURES.includes(o.error.failure),
        `${label}: failure ${JSON.stringify(o.error.failure)} is outside the closed StrideFailure set`,
    ).toBe(true);
    expect(
        o.error.recovery.length > 0,
        `${label}: recovery must name what to do instead, got ${JSON.stringify(o.error.recovery)}`,
    ).toBe(true);
}

// ── fixtures ───────────────────────────────────────────────────────────────

function mulberry32(seed: number): () => number {
    let a = seed >>> 0;
    return () => {
        a = (a + 0x6d2b79f5) >>> 0;
        let t = a;
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

/**
 * `n` bytes with no structure a wrong-offset read could hide behind. Seeded, so
 * a failure names a document that can be rebuilt exactly.
 */
function noisyBytes(seed: number, n: number): Buffer {
    const rnd = mulberry32(seed);
    const out = Buffer.allocUnsafe(n);
    for (let i = 0; i < n; i++) out[i] = Math.floor(rnd() * 256) & 0xff;
    return out;
}

/** Every byte offset in `[0, size]`, as a plain array. */
function everyOffset(size: number): number[] {
    return Array.from({ length: size + 1 }, (_, i) => i);
}

/**
 * Force a full collection, and say whether one was actually obtained.
 *
 * `--expose-gc` on the runner is not assumed: `v8.setFlagsFromString` plus a
 * fresh context is the way to reach a collector regardless of how the process
 * was invoked, so a retained-memory reading cannot quietly depend on a flag
 * somebody has to remember. Returning a boolean rather than silently doing
 * nothing is the point -- a reading taken without a collection is a reading of
 * the collector's schedule, and the caller asserts on this before believing it.
 */
function forceCollection(): boolean {
    v8.setFlagsFromString('--expose_gc');
    const collect: unknown = vm.runInNewContext('gc');
    if (typeof collect !== 'function') return false;
    // Twice: the first pass can leave freshly-unreachable external memory for
    // the second to release, and `arrayBuffers` counts external memory.
    collect();
    collect();
    return true;
}

// ── discovering the implementation's own seams ─────────────────────────────

/**
 * The page size FileSource uses, read out of its own residency accounting
 * rather than restated from source.ts. One byte read faults exactly one page in,
 * and `residentBytes` is `pages.size * PAGE_BYTES`, so with one page resident it
 * IS the page size.
 *
 * Discovery runs at module load, where `expect` is not available, so an
 * impossible answer throws instead. Its properties are asserted in a test.
 */
function discoverPageBytes(): number {
    const p = tmpPath('discover-page.bin');
    fs.writeFileSync(p, noisyBytes(1, 8 << 20));
    const src = new FileSource(p, 8);
    try {
        if (src.stats.residentBytes !== 0) throw new Error('a fresh FileSource already held pages');
        if (src.byteAt(0) < 0) throw new Error('reading byte 0 of an 8 MiB document failed');
        const page = src.stats.residentBytes;
        if (src.stats.misses !== 1) throw new Error(`one byte read faulted ${src.stats.misses} pages, not 1`);
        if (page <= 0) throw new Error(`discovered a non-positive page size: ${page}`);
        return page;
    } finally {
        src.close();
    }
}

/** The chunk size `sequential` hands out, taken from what it actually hands out. */
function discoverChunkBytes(pageBytes: number): number {
    const size = 16 * pageBytes;
    const p = tmpPath('discover-chunk.bin');
    fs.writeFileSync(p, noisyBytes(2, size));
    const src = new FileSource(p, 4);
    try {
        const lens: number[] = [];
        src.sequential(0, size, (chunk) => { lens.push(chunk.length); });
        if (lens.length < 2) throw new Error(`sequential handed a ${size}-byte document over in one piece`);
        const first = lens[0] ?? 0;
        if (first <= 0) throw new Error('the first chunk was empty');
        return first;
    } finally {
        src.close();
    }
}

const PAGE_BYTES = discoverPageBytes();
const CHUNK_BYTES = discoverChunkBytes(PAGE_BYTES);

