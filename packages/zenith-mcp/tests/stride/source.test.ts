describe('I6: a file-backed document is served without being materialised', () => {
    it('holds no more than its page budget while serving a document many times larger', () => {
        // The structural half of I6. `residentBytes` is computed from the live
        // page map, so this is a measurement of the cache, not a restatement of
        // a constant -- and the slices are checked byte for byte at the same
        // time, so "it stayed small" cannot be satisfied by serving nothing.
        const size = 64 * PAGE_BYTES;
        const bytes = noisyBytes(51, size);
        const pages = 4;
        const src = fileSourceOver('bounded.bin', bytes, pages);
        const READ_BYTES = 4096;
        // The read count is DERIVED from the property, never chosen. Serving
        // less than the document proves nothing: a cache that accumulated every
        // page it ever touched would also stay under budget, as long as the
        // sweep never asked for more than fits. 5/4 of the document, so pages
        // are provably re-read after eviction rather than merely held.
        //
        // A fixed 2,000 reads could not reach that at any page size --
        // 2,000 x 4,096 = 8,192,000 bytes against a 67,108,864-byte document --
        // so the precondition below failed on this test's own arithmetic rather
        // than on anything the reader did. Deriving it means the sweep cannot
        // silently stop covering what it claims to cover if a size moves.
        const reads = Math.ceil((size * 5) / (4 * READ_BYTES));
        const rnd = mulberry32(0xb0_11_1d);
        let served = 0;
        let peakResident = 0;
        let peakAfter = 0;
        const touched = new Set<number>();
        for (let i = 0; i < reads; i++) {
            const start = Math.floor(rnd() * (size - READ_BYTES));
            const end = start + READ_BYTES;
            seenRange(start, end);
            expect(
                src.slice(start, end).equals(bytes.subarray(start, end)),
                `slice(${start}, ${end}) must be verbatim while the cache is under pressure`,
            ).toBe(true);
            served += end - start;
            touched.add(Math.floor(start / PAGE_BYTES));
            // Sampled at every read and asserted once, on the peak: identical
            // coverage to an assertion per read, and it names the read the
            // ceiling was breached at instead of only the last one.
            const resident = src.stats.residentBytes;
            if (resident > peakResident) { peakResident = resident; peakAfter = i + 1; }
        }
        expect(
            peakResident,
            `the cache must hold at most ${pages} pages at every point of the sweep; it peaked at ${peakResident} bytes after read ${peakAfter} of ${reads}`,
        ).toBeLessThanOrEqual(pages * PAGE_BYTES);
        expect(touched.size > pages * 4, `the reads must span far more pages (${touched.size}) than fit in the cache (${pages})`).toBe(true);
        expect(served > size, `more bytes must be served (${served}) than the document holds (${size})`).toBe(true);
        expect(src.stats.misses > pages, 'the cache must actually have faulted and evicted').toBe(true);
        console.log(`[I6] served ${served} bytes of a ${size}-byte document over ${reads} reads across ${touched.size} pages; resident peak ${peakResident} of a ${pages * PAGE_BYTES}-byte ceiling; ${src.stats.hits} hits / ${src.stats.misses} misses`);
    }, 300_000);

    it('serves a 64 MiB document while holding a few MiB of it live, where the buffer-backed source holds all 64 MiB', () => {
        // The differential is the right idea and it is kept: measuring only the
        // file-backed pass would prove nothing, because a measurement that reads
        // zero for everything also reads small, so the buffer-backed control is
        // REQUIRED to show the whole document.
        //
        // THE INSTRUMENT WAS THE DEFECT HERE, not the reader. A first draft
        // asserted on the growth of `process.memoryUsage().arrayBuffers` across
        // the pass. That counter reports Buffer memory ALLOCATED AND NOT YET
        // RECLAIMED, and the page cache allocates a fresh 1 MiB page on every
        // fault -- 476 faults over this workload, churning 476 MiB through a
        // cache that holds 4 MiB. The raw growth therefore measures the
        // collector's schedule, not the reader's footprint. Over five identical
        // runs of this exact workload it read 73, 77, 95, 84 and 73 MiB: every
        // one of them ABOVE the 64 MiB document, on a reader whose live pages
        // never exceeded 4 MiB. No threshold can be chosen over that spread that
        // asserts anything, and one chosen to accommodate it would assert less
        // than nothing.
        //
        // What replaces it needs no collector at all: the largest buffer either
        // source must hold live to serve a full pass, taken from the same call on
        // both. FileSource hands out scan chunks of a size fixed by the reader
        // and keeps at most `maxPages` pages; BufferSource hands the whole
        // document over in one chunk, because it holds the whole document. Same
        // measurement, same code path, and the control still proves the
        // measurement can SEE a materialised document. A retained-memory
        // differential follows as an independent cross-check -- it is what the
        // original tried to measure -- taken after forcing a collection, so it
        // reads retention instead of schedule. That one came out at exactly
        // 4.00 MiB against 64.00 MiB on all five runs.
        const MiB = 1 << 20;
        const size = 64 * MiB;
        const p = tmpPath('mem64.bin');
        const block = noisyBytes(52, MiB);
        const fd = fs.openSync(p, 'w');
        for (let i = 0; i < 64; i++) {
            // Vary each block so the document is not 64 copies of one megabyte.
            const b = Buffer.from(block);
            b[0] = i & 0xff;
            b[MiB - 1] = (i * 7) & 0xff;
            fs.writeSync(fd, b, 0, MiB, i * MiB);
        }
        fs.closeSync(fd);

        const truth = fs.readFileSync(p);
        expect(truth.length, 'the fixture is 64 MiB').toBe(size);
        const checksum = (buf: Buffer, from: number, to: number): number => {
            let h = 0;
            for (let i = from; i < to; i += 997) h = (h + (buf[i] ?? 0)) % 1_000_003;
            return h;
        };
        const wanted = checksum(truth, 0, size);
        const arrayBuffersNow = (): number => process.memoryUsage().arrayBuffers;

        // ── file-backed: a full sequential pass plus 500 random slices ──
        expect(
            forceCollection(),
            'the retained-memory cross-check needs a real collector; without one the reading is of the collector\'s schedule, not of retention',
        ).toBe(true);
        const retainedBeforeFile = arrayBuffersNow();
        const pages = 4;
        const filed = new FileSource(p, pages);
        OPEN_SOURCES.push(filed);
        let got = 0;
        let cursor = 0;
        let fileMaxChunk = 0;
        let filePeakResident = 0;
        filed.sequential(0, size, (chunk, absolute) => {
            expect(absolute, 'the sequential pass must stay contiguous').toBe(cursor);
            fileMaxChunk = Math.max(fileMaxChunk, chunk.length);
            filePeakResident = Math.max(filePeakResident, filed.stats.residentBytes);
            for (let i = 0; i < chunk.length; i++) {
                const at = absolute + i;
                if (at % 997 === 0) got = (got + (chunk[i] ?? 0)) % 1_000_003;
            }
            cursor += chunk.length;
        });
        expect(cursor, 'the pass covered the whole document').toBe(size);
        expect(got, 'and delivered the same bytes a full read of the file holds').toBe(wanted);
        const rnd = mulberry32(0xfa11);
        for (let i = 0; i < 500; i++) {
            const start = Math.floor(rnd() * (size - 8192));
            expect(
                filed.slice(start, start + 8192).equals(truth.subarray(start, start + 8192)),
                `random slice at ${start} of the 64 MiB document must be verbatim`,
            ).toBe(true);
            filePeakResident = Math.max(filePeakResident, filed.stats.residentBytes);
        }
        expect(
            filePeakResident,
            `the page cache must hold at most its ${pages}-page budget at every point of the pass; it peaked at ${filePeakResident} bytes`,
        ).toBeLessThanOrEqual(pages * PAGE_BYTES);
        forceCollection();
        const retainedWithFile = arrayBuffersNow();
        filed.close();

        // ── buffer-backed: the control, which DOES materialise the document ──
        forceCollection();
        const retainedBeforeBuf = arrayBuffersNow();
        const buffered = new BufferSource(fs.readFileSync(p), 'mem64-buffer');
        let got2 = 0;
        let bufMaxChunk = 0;
        buffered.sequential(0, size, (chunk, absolute) => {
            bufMaxChunk = Math.max(bufMaxChunk, chunk.length);
            for (let i = 0; i < chunk.length; i++) {
                const at = absolute + i;
                if (at % 997 === 0) got2 = (got2 + (chunk[i] ?? 0)) % 1_000_003;
            }
        });
        expect(got2, 'the buffer-backed pass read the same document').toBe(wanted);
        forceCollection();
        const retainedWithBuf = arrayBuffersNow();

        const fileRetained = Math.max(0, retainedWithFile - retainedBeforeFile);
        const bufRetained = Math.max(0, retainedWithBuf - retainedBeforeBuf);
        // Not simultaneously live -- the scan buffer is released before the
        // slices run -- so their sum is an upper bound on the file-backed
        // source's live footprint, which is the direction that has to be safe.
        const fileLivePeak = filePeakResident + fileMaxChunk;
        console.log(`[I6] 64 MiB document: file-backed largest chunk ${fileMaxChunk} B, resident peak ${filePeakResident} B, live bound ${(fileLivePeak / MiB).toFixed(2)} MiB, retained after collection ${(fileRetained / MiB).toFixed(2)} MiB; buffer-backed largest chunk ${bufMaxChunk} B, retained ${(bufRetained / MiB).toFixed(2)} MiB`);

        // The control half, on the deterministic measurement: the same call on a
        // source that really does hold the document reports the document.
        expect(
            bufMaxChunk,
            `the measurement must be able to SEE a materialised document: the buffer-backed pass held ${bufMaxChunk} bytes of the ${size}-byte document in one chunk`,
        ).toBe(size);
        // And the claim. CHUNK_BYTES was discovered from a 16-page document, so a
        // chunk that still measures exactly that over a document four times
        // larger is fixed by the reader and is not scaling with the document.
        expect(
            fileMaxChunk,
            `the file-backed pass must chunk by a size the reader fixes, not by the document: it handed over ${fileMaxChunk} bytes at once, where a 16-page document produced ${CHUNK_BYTES}`,
        ).toBe(CHUNK_BYTES);
        expect(
            fileLivePeak * 4 < size,
            `every buffer the file-backed source holds at once -- ${pages} pages of ${PAGE_BYTES} plus one ${fileMaxChunk}-byte chunk, ${fileLivePeak} bytes -- must be a small fraction of the ${size}-byte document`,
        ).toBe(true);

        // The cross-check, on retained bytes. Both bounds come from the reader's
        // own structure rather than from what happened to pass: the control must
        // retain the document it holds, and the file-backed source must retain no
        // more than the pages and chunk it is accounted for above.
        expect(
            bufRetained,
            `the control must retain the document it holds: it retained ${(bufRetained / MiB).toFixed(2)} MiB of a ${size / MiB} MiB document`,
        ).toBeGreaterThan(60 * MiB);
        expect(
            fileRetained,
            `the file-backed source must retain only its own pages and chunk, ${fileLivePeak} bytes at most; it retained ${(fileRetained / MiB).toFixed(2)} MiB where the control retained ${(bufRetained / MiB).toFixed(2)} MiB of the same document`,
        ).toBeLessThanOrEqual(fileLivePeak);
        fs.rmSync(p, { force: true });
    }, 300_000);

    it('returns a view onto its own storage for a slice inside one page, so a read costs no copy', () => {
        // Pinned because it is load-bearing for I6: the single-page path is
        // documented as returning a view rather than a copy, and a change to a
        // copy would turn every read into an allocation.
        const bytes = noisyBytes(53, 4096);
        const buffered = new BufferSource(bytes, 'view-buffer');
        const view = buffered.slice(100, 200);
        expect(view.buffer === bytes.buffer, 'BufferSource returns a view onto the caller\'s own bytes').toBe(true);
        const filed = fileSourceOver('view.bin', bytes, 2);
        const a = filed.slice(100, 200);
        const b = filed.slice(150, 250);
        expect(
            a.buffer === b.buffer,
            'two slices inside the same cached page are views onto that one page, not two copies',
        ).toBe(true);
        expect(a.equals(bytes.subarray(100, 200)), 'and the view is still the document bytes').toBe(true);
    });
});

