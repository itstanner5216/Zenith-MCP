// ---------------------------------------------------------------------------
// tests/stride/source.test.ts — invariant I1 (SOURCE TRUTH) and I6 (BOUNDED
// MEMORY) at the layer everything else stands on.
//
// I1 says every rendered document value is a VERBATIM byte slice of the source.
// Nothing above this module can honour that if `slice` is off by one, so the
// property asserted here is not "slice returns something plausible" but
// "slice(start, end) equals the underlying bytes over that range", checked
// against a Buffer this file assembled, for every boundary a small document
// has and for every seam a large one has.
//
// Two implementations satisfy one interface and they must be interchangeable,
// so every fidelity test runs against both and against each other. FileSource
// serves reads through a page cache and copies across page boundaries by hand,
// which is where an off-by-one lives; BufferSource returns subarrays and cannot
// have that class of bug. Comparing them catches what comparing either against
// itself would not.
//
// THE FIXTURE IS PART OF THE TEST. A first draft of these tests generated bytes
// as `(i * 131 + (i >>> 11)) & 0xff`, which is periodic with a period that
// divides the page size -- so a read that returned the RIGHT LENGTH from the
// WRONG PAGE compared equal and the test passed. That is precisely the defect
// class this file exists to catch. Every fixture here is therefore driven by a
// seeded mulberry32 PRNG, and `it does not repeat itself at any page or chunk
// seam` asserts the non-periodicity directly, so the fixture cannot silently
// stop being able to detect a wrong-offset read.
//
// The internal page size and scan chunk size are not exported. They are
// DISCOVERED at runtime -- the page size from `FileSource.stats.residentBytes`
// after a single byte read, the chunk size from the lengths `sequential` hands
// the callback -- rather than restated as literals here, because a seam test
// that hard-codes the seam stops testing the seam the day the constant moves.
//
// I6 is asserted as a differential, which is the only way a memory assertion
// means anything: the same instrument (`process.memoryUsage().arrayBuffers`,
// which counts Buffer memory, unlike heapUsed) is pointed at a file-backed pass
// over a 64 MiB document and at a buffer-backed one. The buffer-backed pass is
// REQUIRED to show the document's full size, which proves the instrument can
// see materialisation at all; the file-backed pass is then required to show a
// small fraction of it. A one-sided "it stayed small" assertion would pass
// against a broken instrument.
// ---------------------------------------------------------------------------

