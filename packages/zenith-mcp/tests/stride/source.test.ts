describe('the fixtures these tests depend on', () => {
    it('does not repeat itself at any page or chunk seam, so a wrong-page read cannot compare equal', () => {
        // The guard on the guard. If this ever fails, every byte-fidelity test
        // below has quietly stopped being able to detect a read from the wrong
        // offset, which is the exact failure mode of the 32-bit page shift.
        const size = 4 * PAGE_BYTES + 1234;
        const bytes = noisyBytes(7, size);
        const window = 4096;
        for (const shift of [PAGE_BYTES, 2 * PAGE_BYTES, 3 * PAGE_BYTES, CHUNK_BYTES,
            PAGE_BYTES - 1, PAGE_BYTES + 1]) {
            if (shift + window > size) continue;
            const a = bytes.subarray(0, window);
            const b = bytes.subarray(shift, shift + window);
            expect(
                a.equals(b),
                `the fixture repeats after ${shift} bytes, so a read from the wrong page would pass unnoticed`,
            ).toBe(false);
        }
        const distinct = new Set(bytes.subarray(0, 4096));
        expect(distinct.size > 200, `the fixture must use most byte values, saw ${distinct.size} of 256`).toBe(true);
    }, 60_000);

    it('reports a page size and a chunk size discovered from the implementation, not restated', () => {
        expect(PAGE_BYTES >= 4096, `the discovered page size must be plausible, got ${PAGE_BYTES}`).toBe(true);
        expect(
            (PAGE_BYTES & (PAGE_BYTES - 1)) === 0,
            `the page size must be a power of two, since it is reached by a shift; got ${PAGE_BYTES}`,
        ).toBe(true);
        expect(
            CHUNK_BYTES >= PAGE_BYTES,
            `the scan chunk (${CHUNK_BYTES}) must be at least a page (${PAGE_BYTES})`,
        ).toBe(true);
        console.log(`[seams] discovered PAGE_BYTES=${PAGE_BYTES} SCAN_CHUNK_BYTES=${CHUNK_BYTES}`);
    });
});

describe('I1: slice returns the document bytes verbatim', () => {
    it('matches the underlying bytes for every start and end of a small document, in both implementations', () => {
        // Exhaustive: all 2,145 ranges of a 64-byte document, twice over.
        const size = 64;
        const bytes = noisyBytes(11, size);
        const buffered = new BufferSource(bytes, 'exhaustive-buffer');
        const filed = fileSourceOver('exhaustive.bin', bytes, 4);
        let checked = 0;
        for (const start of everyOffset(size)) {
            for (let end = start; end <= size; end++) {
                seenRange(start, end);
                const want = bytes.subarray(start, end);
                const fromBuffer = buffered.slice(start, end);
                const fromFile = filed.slice(start, end);
                expect(
                    fromBuffer.equals(want),
                    `BufferSource.slice(${start}, ${end}) must be the document's own bytes; got ${fromBuffer.toString('hex')} want ${want.toString('hex')}`,
                ).toBe(true);
                expect(
                    fromFile.equals(want),
                    `FileSource.slice(${start}, ${end}) must be the document's own bytes; got ${fromFile.toString('hex')} want ${want.toString('hex')}`,
                ).toBe(true);
                expect(
                    fromFile.equals(fromBuffer),
                    `the two implementations must agree on slice(${start}, ${end})`,
                ).toBe(true);
                expect(fromBuffer.length, `slice(${start}, ${end}) must be exactly ${end - start} bytes long`)
                    .toBe(end - start);
                checked++;
            }
        }
        expect(checked, 'every range of a 64-byte document was checked: 65 * 66 / 2').toBe(2145);
    });

    it('returns an empty buffer when start equals end, at every offset', () => {
        const size = 64;
        const bytes = noisyBytes(12, size);
        const buffered = new BufferSource(bytes, 'empty-buffer');
        const filed = fileSourceOver('empty.bin', bytes, 4);
        for (const i of everyOffset(size)) {
            seenRange(i, i);
            expect(buffered.slice(i, i).length, `BufferSource.slice(${i}, ${i}) is empty`).toBe(0);
            expect(filed.slice(i, i).length, `FileSource.slice(${i}, ${i}) is empty`).toBe(0);
        }
    });

    it('returns the first and the last byte of a document as themselves', () => {
        const bytes = noisyBytes(13, 1000);
        const first = bytes[0] ?? -1;
        const last = bytes[999] ?? -1;
        for (const [name, src] of [
            ['BufferSource', new BufferSource(bytes, 'ends-buffer')],
            ['FileSource', fileSourceOver('ends.bin', bytes, 4)],
        ] as readonly [string, StrideSource][]) {
            seenRange(0, 1);
            seenRange(999, 1000);
            expect(src.slice(0, 1)[0], `${name}: the first byte of the document`).toBe(first);
            expect(src.slice(999, 1000)[0], `${name}: the last byte of the document`).toBe(last);
            expect(src.slice(0, 1000).equals(bytes), `${name}: the whole document, verbatim`).toBe(true);
        }
    });

    it('agrees with the raw bytes on every offset of a document spanning several pages', () => {
        const size = 3 * PAGE_BYTES + 12_345;
        const bytes = noisyBytes(14, size);
        const buffered = new BufferSource(bytes, 'multi-page-buffer');
        const filed = fileSourceOver('multi-page.bin', bytes, 4);
        // A pseudo-random walk over the whole document plus every seam
        // neighbourhood, so the sweep covers the interior as well as the edges.
        const rnd = mulberry32(0x51ce);
        const starts = new Set<number>();
        for (let p = 0; p <= 4; p++) {
            for (const d of [-2, -1, 0, 1, 2]) {
                const at = p * PAGE_BYTES + d;
                if (at >= 0 && at <= size) starts.add(at);
            }
        }
        for (let i = 0; i < 600; i++) starts.add(Math.floor(rnd() * (size + 1)));
        for (const start of starts) {
            for (const len of [0, 1, 2, 7, 4096, PAGE_BYTES, PAGE_BYTES + 1, 2 * PAGE_BYTES + 3]) {
                const end = Math.min(start + len, size);
                seenRange(start, end);
                const want = bytes.subarray(start, end);
                const gotFile = filed.slice(start, end);
                const gotBuf = buffered.slice(start, end);
                expect(
                    gotFile.equals(want),
                    `FileSource.slice(${start}, ${end}) across ${Math.floor(start / PAGE_BYTES)}..${Math.floor(Math.max(start, end - 1) / PAGE_BYTES)} must be verbatim`,
                ).toBe(true);
                expect(gotBuf.equals(want), `BufferSource.slice(${start}, ${end}) must be verbatim`).toBe(true);
            }
        }
    }, 120_000);

    it('crosses a page seam byte for byte: one before, exactly at, one after, and a whole page along', () => {
        const size = 5 * PAGE_BYTES;
        const bytes = noisyBytes(15, size);
        const filed = fileSourceOver('seam.bin', bytes, 2);   // 2 pages: forces eviction
        const buffered = new BufferSource(bytes, 'seam-buffer');
        for (let seam = PAGE_BYTES; seam < size; seam += PAGE_BYTES) {
            for (const from of [seam - 1, seam, seam + 1, seam - PAGE_BYTES, seam - 3, seam + 3]) {
                if (from < 0) continue;
                for (const to of [from, from + 1, from + 2, seam, seam + 1, from + PAGE_BYTES,
                    from + PAGE_BYTES + 1, Math.min(from + 2 * PAGE_BYTES, size)]) {
                    const end = Math.min(Math.max(to, from), size);
                    seenRange(from, end);
                    const want = bytes.subarray(from, end);
                    expect(
                        filed.slice(from, end).equals(want),
                        `FileSource.slice(${from}, ${end}) around the seam at ${seam} must be verbatim`,
                    ).toBe(true);
                    expect(
                        buffered.slice(from, end).equals(want),
                        `BufferSource.slice(${from}, ${end}) around the seam at ${seam} must be verbatim`,
                    ).toBe(true);
                }
            }
        }
        expect(filed.stats.misses > 5, 'a 2-page cache over 5 pages must really have faulted and evicted').toBe(true);
    }, 120_000);

    it('serves the same bytes on a second read of a page it has already evicted', () => {
        const size = 6 * PAGE_BYTES;
        const bytes = noisyBytes(16, size);
        const filed = fileSourceOver('evict.bin', bytes, 2);
        const probes = [0, PAGE_BYTES, 5 * PAGE_BYTES, 0, 3 * PAGE_BYTES, 0];
        for (const at of probes) {
            const end = Math.min(at + 64, size);
            seenRange(at, end);
            expect(
                filed.slice(at, end).equals(bytes.subarray(at, end)),
                `slice(${at}, ${end}) must be identical whether or not its page is still cached`,
            ).toBe(true);
        }
        expect(filed.stats.residentBytes, 'the cache must still hold no more than its 2-page budget')
            .toBeLessThanOrEqual(2 * PAGE_BYTES);
    });
});

